/**
 * Build the choropleth's committed artefacts from Natural Earth's 110m atlas: the geometry the map
 * fetches, and ISO alpha-2 (what GA reports) → the atlas's ISO-numeric id. Nothing in either file
 * bridges the two, so the bridge is generated and pinned by tests/unit/gaBreakdowns.test.ts.
 *
 * Run: node scripts/gen-world-topology.mjs   (needs network; the outputs are committed)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json';

/** Natural Earth abbreviates, so `Intl.DisplayNames` cannot match these by name. */
const BY_NUMERIC = {
  EH: '732', US: '840', CD: '180', DO: '214', FK: '238', TF: '260', CF: '140', CG: '178',
  GQ: '226', PS: '275', MM: '104', TR: '792', SB: '090', BA: '070', MK: '807', TT: '780',
  SS: '728',
};

const norm = (s) => s.toLowerCase().replace(/[^a-z]/g, '');

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} → HTTP ${res.status}`);
const topo = await res.json();
if (topo.type !== 'Topology' || !topo.objects?.countries) throw new Error('not a countries topology');

// `land` duplicates the coastline and nothing draws it; Antarctica is ink for a row nobody reports.
delete topo.objects.land;
topo.objects.countries.geometries = topo.objects.countries.geometries.filter((g) => g.id !== '010');

mkdirSync(join(root, 'public/geo'), { recursive: true });
writeFileSync(join(root, 'public/geo/countries-110m.json'), JSON.stringify(topo));

const display = new Intl.DisplayNames(['en'], { type: 'region' });
const alpha2 = [];
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    let name;
    try { name = display.of(code); } catch { continue; }
    if (name && name !== code) alpha2.push([code, name]);
  }
}

const byName = new Map(topo.objects.countries.geometries.map((g) => [norm(g.properties.name), g.id]));
const byId = new Set(topo.objects.countries.geometries.map((g) => g.id));
const map = {};
for (const [code, name] of alpha2) {
  const id = BY_NUMERIC[code] ?? byName.get(norm(name));
  if (id && byId.has(id)) map[code] = id;
}

const unreachable = [...byId].filter((id) => id !== null && !Object.values(map).includes(id));
const lines = [
  '// GENERATED by scripts/gen-world-topology.mjs — do not edit.',
  '// ISO-3166-1 alpha-2 (what GA4 reports) → the country id in public/geo/countries-110m.json.',
  '',
  'export const COUNTRY_TOPO_ID: Readonly<Record<string, string>> = {',
  ...Object.keys(map).sort().map((c) => `  ${c}: '${map[c]}',`),
  '};',
  '',
  '/** Atlas shapes no alpha-2 code reaches — drawn, never highlighted. */',
  `export const UNREACHABLE_TOPO_IDS: readonly string[] = [${unreachable.filter(Boolean).map((i) => `'${i}'`).join(', ')}];`,
  '',
];
writeFileSync(join(root, 'src/components/core/Profile/seo/countryTopoIds.generated.ts'), lines.join('\n'));

console.log(`countries: ${topo.objects.countries.geometries.length}, mapped alpha-2: ${Object.keys(map).length}, unreachable shapes: ${unreachable.filter(Boolean).length}`);
