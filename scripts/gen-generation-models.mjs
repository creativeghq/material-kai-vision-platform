#!/usr/bin/env node
/**
 * Projects public.generation_models into src/config/generationModels.generated.ts.
 *
 * WHY A COMMITTED SNAPSHOT AND NOT A LIVE READ.
 * The guard test (tests/unit/generationModelRegistry.test.ts) has to run in CI, where there is no
 * database. A test that silently skipped without credentials would be worse than no test — it
 * would report green on every PR while enforcing nothing. So the registry is projected into a
 * committed file and the test cross-references *code* against *that file*. Same contract as
 * src/integrations/supabase/types.ts and toolManifest.generated.ts: generated source, committed,
 * regenerated by a human, never by CI.
 *
 * AUTH. generation_models is readable by `authenticated` only (it is platform config — an anon
 * reader could enumerate every model slug we can bill against), so the local anon key in .env is
 * NOT enough. Supply a service-role key:
 *
 *     SUPABASE_SERVICE_ROLE_KEY=... node scripts/gen-generation-models.mjs
 *
 * Or, when you already have the rows (an MCP query, psql, the dashboard), skip the fetch:
 *
 *     node scripts/gen-generation-models.mjs --from-json rows.json
 *
 * Both paths run the same serializer, so the output is identical either way — which is the point:
 * a regeneration must not produce a spurious diff just because it took a different route.
 *
 * RUN THIS after any INSERT/UPDATE/DELETE on generation_models. A stale file is a red build.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'config', 'generationModels.generated.ts');

const COLUMNS = [
  'id', 'display_name', 'capability', 'sub_capability', 'provider', 'slug', 'version',
  'adapter', 'input_requirements', 'pricing_key', 'tier', 'status', 'enabled', 'sort_order',
];

async function fetchRows() {
  const url = process.env.SUPABASE_URL || 'https://bgbavxtjlbvgplozizxu.supabase.co';
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) {
    console.error(
      'SUPABASE_SERVICE_ROLE_KEY is not set.\n' +
      'generation_models is authenticated-only, so the anon key in .env cannot read it.\n' +
      'Either export a service-role key, or pass rows you already have:\n' +
      '    node scripts/gen-generation-models.mjs --from-json rows.json',
    );
    process.exit(1);
  }
  const res = await fetch(
    `${url}/rest/v1/generation_models?select=${COLUMNS.join(',')}&order=sort_order.asc`,
    { headers: { apikey: key, Authorization: `Bearer ${key}` } },
  );
  if (!res.ok) {
    console.error(`Supabase REST ${res.status}: ${await res.text()}`);
    process.exit(1);
  }
  return res.json();
}

function serialize(rows) {
  // Sort by sort_order then id so the file is stable regardless of how the rows arrived. An
  // unstable generator produces diff noise, and diff noise is how a real change gets waved through.
  const sorted = [...rows].sort(
    (a, b) => (a.sort_order - b.sort_order) || String(a.id).localeCompare(String(b.id)),
  );
  const picked = sorted.map((r) => Object.fromEntries(COLUMNS.map((c) => [c, r[c] ?? null])));

  return `// AUTO-GENERATED by scripts/gen-generation-models.mjs — DO NOT EDIT BY HAND.
// Projection of public.generation_models (issue #4 Phase 1). Regenerate after any registry change:
//     SUPABASE_SERVICE_ROLE_KEY=... npm run models:generate
//
// This carries ROUTING only. Money lives in ai_model_pricing, reached via pricing_key — the
// registry deliberately does not hold a second copy of any price. A null pricing_key means the
// model has NO verified cost anywhere and was left unpriced rather than seeded with a guess.

export interface GenerationModelRow {
  id: string;
  display_name: string;
  capability: 'image' | 'video' | '3d' | 'audio' | 'upscale' | 'bg_removal' | 'lipsync';
  sub_capability: string | null;
  provider: string;
  slug: string | null;
  version: string | null;
  adapter: string | null;
  input_requirements: {
    needs_prompt?: boolean;
    min_images?: number;
    max_images?: number;
    image_roles?: string[];
  };
  pricing_key: string | null;
  tier: 'budget' | 'standard' | 'premium' | null;
  status: 'active' | 'degraded' | 'dead';
  enabled: boolean;
  sort_order: number;
}

export const GENERATION_MODELS: readonly GenerationModelRow[] = ${JSON.stringify(picked, null, 2)} as const;

/** Model ids the registry knows about, for O(1) membership checks. */
export const GENERATION_MODEL_IDS: ReadonlySet<string> = new Set(
  GENERATION_MODELS.map((m) => m.id),
);

/** Only these should ever be offered in a picker — status/enabled is what the health check writes. */
export function selectableModels(capability?: GenerationModelRow['capability']) {
  return GENERATION_MODELS.filter(
    (m) => m.status === 'active' && m.enabled && (!capability || m.capability === capability),
  );
}
`;
}

const flagIdx = process.argv.indexOf('--from-json');
const rows = flagIdx !== -1
  ? JSON.parse(readFileSync(process.argv[flagIdx + 1], 'utf8'))
  : await fetchRows();

if (!Array.isArray(rows) || rows.length === 0) {
  console.error('Refusing to write: got no rows. An empty registry file would disable the guard test.');
  process.exit(1);
}

writeFileSync(OUT, serialize(rows), 'utf8');
console.log(`✎ wrote ${OUT} — ${rows.length} models`);
