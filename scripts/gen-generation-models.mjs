#!/usr/bin/env node
/**
 * Projects public.generation_models into src/config/generationModels.generated.ts.
 *
 * WHY A COMMITTED SNAPSHOT AND NOT A LIVE READ.
 * The guard test (tests/unit/generationModelRegistry.test.ts) has to run in CI, where there is no
 * database. A test that silently skipped without credentials would be worse than no test — it
 * would report green on every PR while enforcing nothing. So the registry is projected into a
 * committed file and the test cross-references *code* against *that file*. Same contract as
 * src/integrations/supabase/types.ts and toolManifest.generated.ts: generated source, committed,
 * regenerated by a human, never by CI.
 *
 * AUTH. generation_models is readable by `authenticated` only (it is platform config — an anon
 * reader could enumerate every model slug we can bill against), so the local anon key in .env is
 * NOT enough. Supply a service-role key:
 *
 *     SUPABASE_SERVICE_ROLE_KEY=... node scripts/gen-generation-models.mjs
 *
 * Or, when you already have the rows (an MCP query, psql, the dashboard), skip the fetch:
 *
 *     node scripts/gen-generation-models.mjs --from-json rows.json
 *
 * Both paths run the same serializer, so the output is identical either way — which is the point:
 * a regeneration must not produce a spurious diff just because it took a different route.
 *
 * RUN THIS after any INSERT/UPDATE/DELETE on generation_models. A stale file is a red build.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { fingerprintRows, PROJECTION_COLUMNS } from './lib/projectionFingerprint.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'config', 'generationModels.generated.ts');

// One definition, shared with the guard test — a second copy here is how the file and the
// check that validates it would drift apart.
const COLUMNS = PROJECTION_COLUMNS;

async function fetchRows() {
  const url = process.env.SUPABASE_URL || 'https://bgbavxtjlbvgplozizxu.supabase.co';
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) {
    console.error(
      'SUPABASE_SERVICE_ROLE_KEY is not set.\n' +
      'generation_models is authenticated-only, so the anon key in .env cannot read it.\n' +
      'Either export a service-role key, or pass rows you already have:\n' +
      '    node scripts/gen-generation-models.mjs --from-json rows.json',
    );
    process.exit(1);
  }
  const res = await fetch(
    `${url}/rest/v1/generation_models?select=${COLUMNS.join(',')}&order=sort_order.asc`,
    { headers: { apikey: key, Authorization: `Bearer ${key}` } },
  );
  if (!res.ok) {
    console.error(`Supabase REST ${res.status}: ${await res.text()}`);
    process.exit(1);
  }
  return res.json();
}


function serialize(rows) {
  // Sort by sort_order then id so the file is stable regardless of how the rows arrived. An
  // unstable generator produces diff noise, and diff noise is how a real change gets waved through.
  const sorted = [...rows].sort(
    (a, b) => (a.sort_order - b.sort_order) || String(a.id).localeCompare(String(b.id)),
  );
  const picked = sorted.map((r) => Object.fromEntries(COLUMNS.map((c) => [c, r[c] ?? null])));

  // `eslint-disable` first, exactly as gen-tool-manifest.mjs does for its two artifacts.
  // The row payload is emitted with JSON.stringify, so every key and string comes out
  // double-quoted and trips the repo's `quotes` rule — ~1,500 errors in one file, which
  // failed `npm run lint` and so blocked the whole deploy job from 2026-08-12 13:11.
  // Escaping our way to single quotes by hand would break on any apostrophe in a
  // display_name; disabling lint on a generated artifact is the established pattern here.
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-generation-models.mjs — DO NOT EDIT BY HAND.
// Projection of public.generation_models (issue #4 Phase 1). Regenerate after any registry change:
//     SUPABASE_SERVICE_ROLE_KEY=... npm run models:generate
//
// This carries ROUTING only. Money lives in ai_model_pricing, reached via pricing_key — the
// registry deliberately does not hold a second copy of any price. A null pricing_key means the
// model has NO verified cost anywhere and was left unpriced rather than seeded with a guess.

export interface GenerationModelRow {
  id: string;
  display_name: string;
  capability: 'image' | 'video' | '3d' | 'audio' | 'upscale' | 'bg_removal' | 'lipsync';
  sub_capability: string | null;
  provider: string;
  slug: string | null;
  version: string | null;
  adapter: string | null;
  input_requirements: {
    needs_prompt?: boolean;
    min_images?: number;
    max_images?: number;
    image_roles?: string[];
  };
  pricing_key: string | null;
  tier: 'budget' | 'standard' | 'premium' | null;
  status: 'active' | 'degraded' | 'dead';
  enabled: boolean;
  sort_order: number;
}

export const GENERATION_MODELS: readonly GenerationModelRow[] = ${JSON.stringify(picked, null, 2)} as const;

/**
 * SHA-256 of the rows above, as the GENERATOR emitted them.
 *
 * The nightly \`dic_detect__generation_registry_projection_stale\` catches the database moving
 * without a regeneration. It cannot catch the opposite — this FILE being edited by hand — because
 * it compares the recorded projection against the live table and never sees the file. CI cannot
 * compare the file to the table either: \`generation_models\` is authenticated-only and no workflow
 * carries a service-role key.
 *
 * So the file carries its own checksum. \`tests/unit/generationModelRegistry.test.ts\` recomputes it
 * from the array above; a hand-edit changes the rows and not this constant, and the build fails.
 * Between the two, both directions of drift are covered without a secret in CI.
 */
export const PROJECTION_FINGERPRINT = '${fingerprintRows(picked)}';

/** Model ids the registry knows about, for O(1) membership checks. */
export const GENERATION_MODEL_IDS: ReadonlySet<string> = new Set(
  GENERATION_MODELS.map((m) => m.id),
);

/** Only these should ever be offered in a picker — status/enabled is what the health check writes. */
export function selectableModels(capability?: GenerationModelRow['capability']) {
  return GENERATION_MODELS.filter(
    (m) => m.status === 'active' && m.enabled && (!capability || m.capability === capability),
  );
}
`;
}


/**
 * Tell the database what we just wrote into the committed file.
 *
 * This is the half of the drift check that cannot live in CI. `gen:all` does not run this script
 * and cannot: `generation_models` is authenticated-only, so the anon key in CI cannot read it, and
 * no workflow carries a service-role key. So nothing compares the committed projection against its
 * source, and it can drift indefinitely with every check green — which it did, until `veo-2` was
 * spotted by hand on 2026-08-17 showing `pricing_key: null` ("no verified cost exists") while the
 * table had it pointed at a live $0.35/unit row.
 *
 * Recording it here means the comparison happens where the credentials already are: nightly, in
 * `dic_detect__generation_registry_projection_stale`. Change the table without regenerating and it
 * fires. Hand-edit the file and tests/unit/generationModelRegistry.test.ts fires instead.
 *
 * Best-effort by design — a failure to record must not stop the file being written, because a
 * written file with no record degrades to "the detector says stale", which is the safe direction.
 */
async function recordProjection(rows) {
  const url = process.env.SUPABASE_URL || 'https://bgbavxtjlbvgplozizxu.supabase.co';
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) {
    console.warn('! no service-role key — projection NOT recorded; the nightly check will report it stale');
    return;
  }

  // The exact shape the file received, sorted identically, so the detector compares like with
  // like. `generation_models_projection_now()` builds the same object server-side.
  const sorted = [...rows].sort(
    (a, b) => (a.sort_order - b.sort_order) || String(a.id).localeCompare(String(b.id)),
  );
  const picked = sorted.map((r) => Object.fromEntries(COLUMNS.map((c) => [c, r[c] ?? null])));

  const res = await fetch(`${url}/rest/v1/generation_models_projection`, {
    method: 'POST',
    headers: {
      apikey: key,
      Authorization: `Bearer ${key}`,
      'Content-Type': 'application/json',
      Prefer: 'resolution=merge-duplicates',
    },
    body: JSON.stringify({
      id: true,
      rows: picked,
      row_count: picked.length,
      generated_at: new Date().toISOString(),
      generated_by: process.env.USER || process.env.USERNAME || 'unknown',
    }),
  });

  if (!res.ok) {
    console.warn(`! could not record the projection (${res.status}): ${await res.text()}`);
    console.warn('  the file is written; the nightly drift check will report it stale until this succeeds');
    return;
  }
  console.log('✓ recorded the projection for the nightly drift check');
}

const flagIdx = process.argv.indexOf('--from-json');
const rows = flagIdx !== -1
  ? JSON.parse(readFileSync(process.argv[flagIdx + 1], 'utf8'))
  : await fetchRows();

if (!Array.isArray(rows) || rows.length === 0) {
  console.error('Refusing to write: got no rows. An empty registry file would disable the guard test.');
  process.exit(1);
}

writeFileSync(OUT, serialize(rows), 'utf8');
console.log(`✎ wrote ${OUT} — ${rows.length} models`);

await recordProjection(rows);
