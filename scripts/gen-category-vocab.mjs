#!/usr/bin/env node
/** Projects public.material_categories into src/lib/categoryVocab.generated.ts. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/lib/categoryVocab.generated.ts');

async function fetchRows() {
  const fromJsonIdx = process.argv.indexOf('--from-json');
  if (fromJsonIdx !== -1) {
    const path = process.argv[fromJsonIdx + 1];
    if (!path) throw new Error('--from-json needs a file path');
    const parsed = JSON.parse(readFileSync(path, 'utf8'));
    return Array.isArray(parsed) ? parsed : parsed.rows;
  }

  const url = process.env.SUPABASE_URL || 'https://bgbavxtjlbvgplozizxu.supabase.co';
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) {
    throw new Error(
      'SUPABASE_SERVICE_ROLE_KEY is not set.\n'
      + 'Either export it, or pass rows you already have:\n'
      + '  node scripts/gen-category-vocab.mjs --from-json rows.json',
    );
  }
  const res = await fetch(
    `${url}/rest/v1/material_categories`
    + '?select=category_key,display_name,controlled_vocab,vocab_aliases&order=category_key',
    { headers: { apikey: key, Authorization: `Bearer ${key}` } },
  );
  if (!res.ok) throw new Error(`material_categories fetch failed: ${res.status} ${await res.text()}`);
  return res.json();
}

const lit = (s) => `'${String(s).split('\\').join('\\\\').split("'").join("\\'")}'`;
const arr = (xs) => `[${(xs ?? []).slice().sort().map(lit).join(', ')}]`;

const rows = (await fetchRows())
  .filter((r) => r && r.category_key)
  .sort((a, b) => a.category_key.localeCompare(b.category_key));

if (!rows.length) {
  throw new Error('material_categories returned no rows — refusing to write an empty vocabulary.');
}

const body = rows.map((r) => `  {
    key: ${lit(r.category_key)},
    displayName: ${lit(r.display_name ?? r.category_key)},
    controlledVocab: ${arr(r.controlled_vocab)},
    aliases: ${arr(r.vocab_aliases)},
  },`).join('\n');

writeFileSync(OUT, `/**
 * GENERATED by scripts/gen-category-vocab.mjs — do not edit.
 *
 * Projection of public.material_categories. Regenerate after changing controlled_vocab or
 * vocab_aliases; tests/unit/categoryVocabRegistry.test.ts fails the build when this is stale
 * or when a second copy of the vocabulary appears in hand-written source (#347 phase 3.4).
 */

export interface CategoryVocabEntry {
  key: string;
  displayName: string;
  /** Canonical values a model may emit for this category. */
  controlledVocab: string[];
  /** Coarse terms that map ONTO this category. Never offered to a model as a choice. */
  aliases: string[];
}

export const CATEGORY_VOCAB: CategoryVocabEntry[] = [
${body}
];

/**
 * Every category key, as a literal tuple so \`UploadCategory\` can be a type rather than a
 * hand-written union that drifts. \`building_materials\` was live in the DB and absent from
 * the union for months, so a door resolved to \`general_materials\` and rendered under the
 * wrong heading (#368 PD-5).
 */
export const CATEGORY_KEYS = [${rows.map((r) => lit(r.category_key)).join(', ')}] as const;

export type CategoryKey = typeof CATEGORY_KEYS[number];

/** Display name per category key, straight from material_categories. */
export const CATEGORY_DISPLAY_NAMES: Record<string, string> = Object.fromEntries(
  CATEGORY_VOCAB.map((c) => [c.key, c.displayName]),
);

/** Every canonical value across all categories. */
export const ALL_CONTROLLED_VOCAB: ReadonlySet<string> = new Set(
  CATEGORY_VOCAB.flatMap((c) => c.controlledVocab),
);

/**
 * Resolve a fine-grained or loose material_category value onto a category key.
 * Canonical values win over aliases, so a term that is both resolves the same way every time.
 */
export function categoryKeyForVocab(value: string): string | null {
  const v = value.trim().toLowerCase();
  if (!v) return null;
  for (const c of CATEGORY_VOCAB) if (c.controlledVocab.includes(v)) return c.key;
  for (const c of CATEGORY_VOCAB) if (c.aliases.includes(v)) return c.key;
  return null;
}
`, 'utf8');

const canonical = rows.reduce((n, r) => n + (r.controlled_vocab?.length ?? 0), 0);
const aliases = rows.reduce((n, r) => n + (r.vocab_aliases?.length ?? 0), 0);
console.log(`✎ wrote src/lib/categoryVocab.generated.ts — ${rows.length} categories, ${canonical} canonical values, ${aliases} aliases`);
